// the same shapes under other names
const SAME = { 'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O',
  'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X', 'І': 'I', 'Ѕ': 'S', 'Ј': 'J', '–': '-', '—': '-' };
// accents, two rows over the letter (combining marks, after NFD)
const ACCENT = {
  '̈': ['.....', '.#.#.'],      // diaeresis: Ӧ Ё Ї
  '̏': ['#..#.', '.#..#'],      // double grave: Ȍ О̏
  '̆': ['#...#', '.###.'],      // breve: Й Ў
  '̀': ['.#...', '..#..'],      // grave
  '́': ['...#.', '..#..'],      // acute
};
export const MATRIX_GLYPH = { w: 5, h: 7, accent: 2, gap: 1, adv: 6 };
const rowsOf = (spec) => spec.split(' ');
// a character's shape: its rows ('#' lit), or null if there is none
export function glyphOf(ch) {
  const c = SAME[ch] || ch;
  return G[c] ? rowsOf(G[c]) : null;
}
// a line of text as letters and the accents over each: [{ rows, accents: [[2 rows]...] }]
export function matrixLetters(text) {
  const out = [];
  for (const ch of text.toUpperCase().normalize('NFD')) {
    if (ACCENT[ch]) { if (out.length) out[out.length - 1].accents.push(ACCENT[ch]); continue; }
    if (/\p{M}/u.test(ch)) continue;                       // a mark we have no shape for: left off
    out.push({ ch, rows: glyphOf(ch) || rowsOf('##### #...# ...#. ..#.. ..#.. ..... ..#..'), known: !!glyphOf(ch), accents: [] });
  }
  return out;
}
// lamps lit by a line of text set at (x, y) (y: the top of its accent rows) on a cols x nrows grid
export function setMatrixText(lit, cols, nrows, text, x, y, alignRight) {
  const L = matrixLetters(text), A = MATRIX_GLYPH;
  if (alignRight) x = x - (L.length * A.adv - A.gap);
  L.forEach((l, i) => {
    const x0 = x + i * A.adv;
    const put = (gx, gy) => { if (gx >= 0 && gx < cols && gy >= 0 && gy < nrows) lit[gy * cols + gx] = 1; };
    for (const acc of l.accents) acc.forEach((r, ry) => { for (let rx = 0; rx < A.w; rx++) if (r[rx] === '#') put(x0 + rx, y + ry); });
    l.rows.forEach((r, ry) => { for (let rx = 0; rx < A.w; rx++) if (r[rx] === '#') put(x0 + rx, y + A.accent + A.gap + ry); });
  });
  return L;
}
