// which voice a guard speaks with: the Yellows by who they are, everyone else by a hash of his id
export function spokenVoice(g, yellowLine) {
  if (g.voice) return g.voice;                          // one with a voice of his own: railway staff, the announcer
  let h = 0; for (const ch of String(g.id)) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  if (yellowLine) return g.boss ? 'yb' : h % 2 ? 'yg1' : 'yg2';
  return h % 2 ? 'r1' : 'r2';
}

